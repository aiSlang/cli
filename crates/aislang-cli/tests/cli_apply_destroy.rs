//! Integration tests for `aislang apply` + `aislang destroy` — Friday
//! of week 6.
//!
//! Categories covered:
//!   1. **Apply with docker available**: writes stack.yml, runs
//!      `docker compose up -d`. We can't reliably bring a real stack
//!      up in CI (needs Docker daemon + image pulls + API keys), so
//!      these tests are `#[ignore]`d. Run locally:
//!        cargo test -p aislang-cli --test cli_apply_destroy -- --ignored
//!
//!   2. **Apply with docker absent** (`PATH=/nonexistent`): apply
//!      writes artifacts then prints the manual `docker compose -f
//!      stack.yml up -d` instruction and exits 0. Validates the
//!      "always produces files even without docker" contract.
//!
//!   3. **Destroy without prior apply**: clean error pointing the
//!      user at `aislang apply` first.
//!
//!   4. **Destroy with docker absent**: hard error (nothing to do
//!      without docker; better to surface than silently no-op).

use std::path::PathBuf;
use std::process::Command;

/// Write a tool-less .ais source + matching prompt file to a unique
/// tempdir. Apply writes its artifacts into this same dir.
/// Caller is responsible for `remove_dir_all`.
fn tempdir_with_project(suffix: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!(
        "aislang-apply-destroy-{}-{suffix}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("mkdir");
    std::fs::write(dir.join("system.md"), "you are helpful").expect("write prompt");
    let src = r#"project "demo" {
  budget {
    hard_cap_per_day = $1
    hard_cap_per_run = $0.01
  }
  model "fast" {
    requires    = [chat]
    context_min = 32k
    prefer      = [ollama.llama_3_1_8b]
    pin         = ollama.llama_3_1_8b
  }
  prompt "system" {
    file    = "./system.md"
    version = "1.0.0"
  }
  agent "support" {
    model         = model.fast
    system_prompt = prompt.system
    tools         = []
  }
}
"#;
    let ais_path = dir.join("demo.ais");
    std::fs::write(&ais_path, src).expect("write demo.ais");
    ais_path
}

fn bin() -> Command {
    Command::new(env!("CARGO_BIN_EXE_aislang"))
}

/// Force `docker` off PATH for the child. Used by the "graceful
/// degrade" tests. We don't unset PATH entirely (the binary itself
/// needs to be loadable from disk regardless), just clobber it to a
/// directory that doesn't contain `docker`.
fn bin_no_docker() -> Command {
    let mut cmd = bin();
    cmd.env("PATH", "/nonexistent-aislang-test-path");
    cmd
}

// ---------------------------------------------------------------------------
// apply — graceful degrade when docker is absent
// ---------------------------------------------------------------------------

#[test] fn apply_without_docker_writes_artifacts_and_prints_manual_command() {
    let ais = tempdir_with_project("apply-no-docker");
    let dir = ais.parent().unwrap().to_path_buf();

    let out = bin_no_docker().args(["apply"]).arg(&ais).output()
        .expect("spawn aislang");

    let _ = std::fs::remove_dir_all(&dir);
    assert!(out.status.success(),
        "apply must exit 0 even without docker; stderr:\n{}",
        String::from_utf8_lossy(&out.stderr));

    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("docker not on PATH"),
        "stderr must explain docker is missing; got:\n{stderr}");
    assert!(stderr.contains("docker compose -f"),
        "stderr must print the manual command; got:\n{stderr}");
    assert!(stderr.contains("stack.yml"),
        "stderr must mention stack.yml; got:\n{stderr}");
}

#[test] fn apply_writes_stack_yml_and_supporting_artifacts() {
    // Even without docker, apply must produce stack.yml + the
    // companion files so the user can hand-run docker compose or
    // copy them somewhere.
    let ais = tempdir_with_project("apply-writes-artifacts");
    let dir = ais.parent().unwrap().to_path_buf();

    let out = bin_no_docker().args(["apply"]).arg(&ais).output()
        .expect("spawn aislang");
    assert!(out.status.success(),
        "apply exit 0; stderr:\n{}", String::from_utf8_lossy(&out.stderr));

    let stack_yml = dir.join("stack.yml");
    assert!(stack_yml.exists(),
        "stack.yml must be written to source dir; not found at {}",
        stack_yml.display());
    let body = std::fs::read_to_string(&stack_yml).expect("read stack.yml");
    assert!(body.starts_with("# Generated by `aislang plan`"),
        "stack.yml must carry the plan header:\n{body}");
    assert!(body.contains("litellm:"), "stack.yml must declare litellm service");

    // Supporting files (already exercised by plan tests, but
    // double-check apply writes them too).
    assert!(dir.join("litellm_config.yaml").exists(),
        "litellm_config.yaml must be written");
    assert!(dir.join(".env.example").exists(),
        ".env.example must be written");
    assert!(dir.join("aislang.lock").exists(),
        "aislang.lock must be written (apply always reconciles)");

    let _ = std::fs::remove_dir_all(&dir);
}

#[test] fn apply_with_nonexistent_source_errors_cleanly() {
    let out = bin_no_docker()
        .args(["apply", "/tmp/aislang-no-such-file-9b2f.ais"])
        .output().expect("spawn");
    assert!(!out.status.success());
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("read"),
        "stderr should mention the read error; got:\n{stderr}");
}

// ---------------------------------------------------------------------------
// destroy — without prior apply, without docker, etc.
// ---------------------------------------------------------------------------

#[test] fn destroy_without_prior_apply_errors_with_clear_message() {
    // No stack.yml in the source dir → clean error pointing at
    // `aislang apply` as the fix.
    let ais = tempdir_with_project("destroy-no-prior-apply");
    let dir = ais.parent().unwrap().to_path_buf();
    let out = bin_no_docker().args(["destroy"]).arg(&ais).output()
        .expect("spawn");
    let _ = std::fs::remove_dir_all(&dir);
    assert!(!out.status.success(),
        "destroy must fail when stack.yml is missing");
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("no stack.yml"),
        "stderr must explain stack.yml is missing; got:\n{stderr}");
    assert!(stderr.contains("aislang apply"),
        "stderr must point at apply as the fix; got:\n{stderr}");
}

#[test] fn destroy_without_docker_errors_with_clear_message() {
    // Pre-create a fake stack.yml so destroy gets past the file
    // check, then run with docker absent.
    let ais = tempdir_with_project("destroy-no-docker");
    let dir = ais.parent().unwrap().to_path_buf();
    std::fs::write(dir.join("stack.yml"), "# placeholder").expect("write fake stack");

    let out = bin_no_docker().args(["destroy"]).arg(&ais).output()
        .expect("spawn");
    let _ = std::fs::remove_dir_all(&dir);
    assert!(!out.status.success(),
        "destroy must fail when docker is missing");
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("docker not on PATH"),
        "stderr must explain docker is missing; got:\n{stderr}");
}

#[test] fn destroy_with_nonexistent_source_dir_errors_cleanly() {
    let out = bin_no_docker()
        .args(["destroy", "/tmp/aislang-no-such-dir-9b2f/demo.ais"])
        .output().expect("spawn");
    assert!(!out.status.success());
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("not readable") || stderr.contains("no stack.yml"),
        "stderr must explain the failure; got:\n{stderr}");
}
