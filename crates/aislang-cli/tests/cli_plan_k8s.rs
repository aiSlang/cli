//! Integration tests for `aislang plan` against `deploy { target =
//! kubernetes }` — Phase 2 Week 14 Tue.
//!
//! Pins the CLI-level wiring decisions for the K8s emit path:
//!
//!   1. `aislang plan <ais>` against a k8s-target project writes
//!      `<output_dir>/manifests/*.yaml` (three files: litellm,
//!      jaeger, budget-counter — Tue's Decision 43.2 scope).
//!   2. Stdout in k8s-mode is the concatenated manifest stream
//!      (`---`-separated YAML), pipeable into `kubectl apply -f -`.
//!      Header comments lead so a human eyeballing the stream knows
//!      what they're looking at.
//!   3. Stderr `generated:` section lists each emitted manifest path
//!      so a user running `aislang plan` interactively sees where the
//!      files landed.
//!   4. `examples/support-agent-k8s.ais` (Tue fixture) parses + plans
//!      cleanly — acts as a forward-compat trip-wire for grammar
//!      breaks that would silently invalidate the K8s demo path.
//!   5. Compose-target projects continue to emit Compose artifacts
//!      (regression check against the v0.1 plan contract).

use std::path::PathBuf;
use std::process::Command;

fn bin() -> Command {
    Command::new(env!("CARGO_BIN_EXE_aislang"))
}

/// Write a minimal k8s-target .ais project to a unique tempdir.
/// Plan writes manifests/ into this same dir.  Caller is
/// responsible for `remove_dir_all` after assertions.
fn tempdir_with_k8s_project(suffix: &str) -> (PathBuf, PathBuf) {
    let dir = std::env::temp_dir().join(format!(
        "aislang-plan-k8s-{}-{suffix}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("mkdir");
    std::fs::write(dir.join("system.md"), "you are helpful").expect("write prompt");
    let src = r#"project "k8s-demo" {
  budget {
    hard_cap_per_day = $1
    hard_cap_per_run = $0.01
  }
  model "fast" {
    requires    = [chat]
    context_min = 32k
    prefer      = [ollama.llama_3_1_8b]
    pin         = ollama.llama_3_1_8b
  }
  prompt "system" {
    file    = "./system.md"
    version = "1.0.0"
  }
  agent "support" {
    model         = model.fast
    system_prompt = prompt.system
    tools         = []
  }
  deploy "prod" {
    target = kubernetes
    expose { port = 8080  web_ui = false }
  }
}
"#;
    let ais_path = dir.join("demo.ais");
    std::fs::write(&ais_path, src).expect("write demo.ais");
    (ais_path, dir)
}

#[test] fn plan_k8s_writes_manifests_directory() {
    let (ais, dir) = tempdir_with_k8s_project("manifests-dir");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    assert!(out.status.success(),
        "plan must succeed against k8s target; stderr:\n{}",
        String::from_utf8_lossy(&out.stderr));

    // Three manifest files land in <dir>/manifests/.
    let manifests_dir = dir.join("manifests");
    for name in ["litellm.yaml", "jaeger.yaml", "budget-counter.yaml"] {
        let p = manifests_dir.join(name);
        assert!(p.exists(),
            "expected manifest `{}` written to {}",
            name, p.display());
        let body = std::fs::read_to_string(&p).expect("read manifest");
        assert!(body.contains("apiVersion:"),
            "manifest `{name}` must contain `apiVersion:`; got:\n{body}");
    }

    let _ = std::fs::remove_dir_all(&dir);
}

#[test] fn plan_k8s_stdout_is_concatenated_yaml_stream() {
    let (ais, dir) = tempdir_with_k8s_project("stdout-stream");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    assert!(out.status.success());

    let stdout = String::from_utf8_lossy(&out.stdout);
    // Header comment — distinguishes the k8s stream from the Compose
    // YAML one.
    assert!(stdout.starts_with("# Generated by `aislang plan` — target = kubernetes"),
        "k8s-mode stdout must lead with the target-kubernetes header; got:\n{}",
        stdout.lines().take(3).collect::<Vec<_>>().join("\n"));
    // Document separator present (every manifest body leads with `---`).
    assert!(stdout.contains("\n---\n"),
        "k8s-mode stdout must contain `---` doc separators; got:\n{stdout}");
    // Each of the three components appears in the stream.
    for kind_or_name in [
        "kind: Deployment",
        "kind: Service",
        "kind: ConfigMap",
        "name: litellm",
        "name: jaeger",
        "name: budget-counter",
    ] {
        assert!(stdout.contains(kind_or_name),
            "k8s-mode stdout must contain `{kind_or_name}`; got:\n{stdout}");
    }

    let _ = std::fs::remove_dir_all(&dir);
}

#[test] fn plan_k8s_stderr_lists_manifest_paths() {
    let (ais, dir) = tempdir_with_k8s_project("stderr-list");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    assert!(out.status.success());

    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("generated:"),
        "stderr must have a `generated:` section; got:\n{stderr}");
    for name in ["litellm.yaml", "jaeger.yaml", "budget-counter.yaml"] {
        assert!(stderr.contains(name),
            "stderr `generated:` block must list `{name}`; got:\n{stderr}");
    }
    // Lockfile path also reported (cross-check: lockfile section
    // still lands when k8s emit runs).
    assert!(stderr.contains("aislang.lock"),
        "stderr must list the lockfile path; got:\n{stderr}");

    let _ = std::fs::remove_dir_all(&dir);
}

#[test] fn plan_k8s_does_not_write_stack_yml() {
    let (ais, dir) = tempdir_with_k8s_project("no-stack-yml");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    assert!(out.status.success());

    // Pure-k8s project: no Compose artifacts written.  Compose
    // co-emission only happens when the project ALSO has a
    // `target = compose` deploy block (mixed-target case — covered
    // by the next test).
    assert!(!dir.join("stack.yml").exists(),
        "stack.yml must NOT be written for a pure-k8s project");
    assert!(!dir.join("litellm_config.yaml").exists(),
        "litellm_config.yaml is Compose-only — not written when no \
         compose target; the config lands inside the ConfigMap instead");
    assert!(!dir.join(".env.example").exists(),
        ".env.example is Compose-only — not written for k8s-only projects");

    let _ = std::fs::remove_dir_all(&dir);
}

#[test] fn plan_against_k8s_example_fixture_works() {
    // The committed examples/support-agent-k8s.ais fixture must
    // parse + plan cleanly.  Forward-compat trip-wire: any grammar
    // change that silently invalidates the k8s demo path fails
    // here.  Mirrors the v0.1 contract for examples/support-agent
    // .ais but under the k8s target.
    let workspace_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("..").join("..");
    let ais = workspace_root.join("examples").join("support-agent-k8s.ais");
    assert!(ais.exists(),
        "examples/support-agent-k8s.ais must exist at {}",
        ais.display());

    // Plan into a tempdir to avoid polluting the examples/ tree.
    let dir = std::env::temp_dir().join(format!(
        "aislang-k8s-fixture-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("mkdir");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    let _ = std::fs::remove_dir_all(&dir);

    assert!(out.status.success(),
        "examples/support-agent-k8s.ais must plan cleanly; stderr:\n{}",
        String::from_utf8_lossy(&out.stderr));
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(stdout.contains("target = kubernetes"),
        "fixture plan stdout must declare k8s target in header");
    assert!(stdout.contains("name: litellm"),
        "fixture plan must emit the litellm Deployment");
}

#[test] fn plan_compose_target_still_emits_stack_yml_regression() {
    // Regression: a Compose-target project (the v0.1 baseline)
    // continues to emit Compose artifacts unchanged.  Pin the
    // v0.1 plan contract against accidental k8s-path takeover.
    let dir = std::env::temp_dir().join(format!(
        "aislang-plan-compose-regression-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("mkdir");
    std::fs::write(dir.join("system.md"), "x").expect("write prompt");
    let src = r#"project "compose-demo" {
  budget {
    hard_cap_per_day = $1
    hard_cap_per_run = $0.01
  }
  model "fast" {
    requires    = [chat]
    context_min = 32k
    prefer      = [ollama.llama_3_1_8b]
    pin         = ollama.llama_3_1_8b
  }
  prompt "system" {
    file    = "./system.md"
    version = "1.0.0"
  }
  agent "support" {
    model         = model.fast
    system_prompt = prompt.system
    tools         = []
  }
  deploy "local" {
    target = compose
  }
}
"#;
    let ais = dir.join("demo.ais");
    std::fs::write(&ais, src).expect("write demo.ais");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    let stdout = String::from_utf8_lossy(&out.stdout).into_owned();
    let stderr = String::from_utf8_lossy(&out.stderr).into_owned();
    let manifests_exists = dir.join("manifests").exists();
    let env_example_exists = dir.join(".env.example").exists();
    let litellm_config_exists = dir.join("litellm_config.yaml").exists();
    let _ = std::fs::remove_dir_all(&dir);

    assert!(out.status.success(),
        "compose-target plan must succeed; stderr:\n{stderr}");
    // v0.1 stdout shape: Compose YAML, leading with the v0.1 header.
    assert!(stdout.starts_with("# Generated by `aislang plan` — do not edit by hand."),
        "Compose stdout header must be unchanged; got first line:\n{}",
        stdout.lines().next().unwrap_or(""));
    assert!(litellm_config_exists, "Compose path must write litellm_config.yaml");
    assert!(env_example_exists,    "Compose path must write .env.example");
    assert!(!manifests_exists,
        "Compose-only project must NOT have a manifests/ directory");
}
