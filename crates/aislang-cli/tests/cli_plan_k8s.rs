//! Integration tests for `aislang plan` against `deploy { target =
//! kubernetes }` — Phase 2 Week 14 Tue.
//!
//! Pins the CLI-level wiring decisions for the K8s emit path:
//!
//!   1. `aislang plan <ais>` against a k8s-target project writes
//!      `<output_dir>/manifests/*.yaml` (three files: litellm,
//!      jaeger, budget-counter — Tue's Decision 43.2 scope).
//!   2. Stdout in k8s-mode is the concatenated manifest stream
//!      (`---`-separated YAML), pipeable into `kubectl apply -f -`.
//!      Header comments lead so a human eyeballing the stream knows
//!      what they're looking at.
//!   3. Stderr `generated:` section lists each emitted manifest path
//!      so a user running `aislang plan` interactively sees where the
//!      files landed.
//!   4. `examples/support-agent-k8s.ais` (Tue fixture) parses + plans
//!      cleanly — acts as a forward-compat trip-wire for grammar
//!      breaks that would silently invalidate the K8s demo path.
//!   5. Compose-target projects continue to emit Compose artifacts
//!      (regression check against the v0.1 plan contract).

use std::path::PathBuf;
use std::process::Command;

fn bin() -> Command {
    Command::new(env!("CARGO_BIN_EXE_aislang"))
}

/// Write a minimal k8s-target .ais project to a unique tempdir.
/// Plan writes manifests/ into this same dir.  Caller is
/// responsible for `remove_dir_all` after assertions.
fn tempdir_with_k8s_project(suffix: &str) -> (PathBuf, PathBuf) {
    let dir = std::env::temp_dir().join(format!(
        "aislang-plan-k8s-{}-{suffix}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("mkdir");
    std::fs::write(dir.join("system.md"), "you are helpful").expect("write prompt");
    let src = r#"project "k8s-demo" {
  budget {
    hard_cap_per_day = $1
    hard_cap_per_run = $0.01
  }
  model "fast" {
    requires    = [chat]
    context_min = 32k
    prefer      = [ollama.llama_3_1_8b]
    pin         = ollama.llama_3_1_8b
  }
  prompt "system" {
    file    = "./system.md"
    version = "1.0.0"
  }
  agent "support" {
    model         = model.fast
    system_prompt = prompt.system
    tools         = []
  }
  deploy "prod" {
    target = kubernetes
    expose { port = 8080  web_ui = false }
  }
}
"#;
    let ais_path = dir.join("demo.ais");
    std::fs::write(&ais_path, src).expect("write demo.ais");
    (ais_path, dir)
}

#[test] fn plan_k8s_writes_manifests_directory() {
    let (ais, dir) = tempdir_with_k8s_project("manifests-dir");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    assert!(out.status.success(),
        "plan must succeed against k8s target; stderr:\n{}",
        String::from_utf8_lossy(&out.stderr));

    // Three manifest files land in <dir>/manifests/.
    let manifests_dir = dir.join("manifests");
    for name in ["litellm.yaml", "jaeger.yaml", "budget-counter.yaml"] {
        let p = manifests_dir.join(name);
        assert!(p.exists(),
            "expected manifest `{}` written to {}",
            name, p.display());
        let body = std::fs::read_to_string(&p).expect("read manifest");
        assert!(body.contains("apiVersion:"),
            "manifest `{name}` must contain `apiVersion:`; got:\n{body}");
    }

    let _ = std::fs::remove_dir_all(&dir);
}

#[test] fn plan_k8s_stdout_is_concatenated_yaml_stream() {
    let (ais, dir) = tempdir_with_k8s_project("stdout-stream");

    let out = bin().args(["plan"]).arg(&ais)
        .args(["--output-dir"]).arg(&dir)
        .output()
        .expect("spawn aislang");

    assert!(out.status.success());

    let stdout = String::from_utf8_lossy(&out.stdout);
    // Header comment — distinguishes the k8s stream from the Compose
    // YAML one.
    assert!(stdout.starts_with("# Generated by `aislang plan` — target = kubernetes"),
        "k8s-mode stdout must lead with the target-kubernetes header; got:\n{}",
        stdout.lines().take(3).collect::<Vec<_>>().join("\n"));
    // Document separator present (every manifest body leads with `---`).
    assert!(stdout.contains("\n---\n"),
        "k8s-mode stdout must contain `---` doc separators; got:\n{stdout}");
    // Each of the three components appears in the stream.
    for kind_or_name in [
        "kind: Deployment",
        "kind: Service",
        "kind: ConfigMap",
        "name: litellm",
        "name: jaeger",
        "name: budget-counter",
    ] {
        assert!(stdout.contains(kind_or_name),
            "k8s-mode stdout must contain `{kind_or_name}`; got:\n{stdout}");
    }

    let _ = std::fs::remove_dir_all(&dir);
}

